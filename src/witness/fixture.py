"""`witness fixture` (W4): pull a slice from a live Neo4j once, shrink it to a deletion-minimal test fixture.

1. `relate pull` copies the slice into a FRESH temp `.rl` (pull refuses a non-empty destination and `:memory:`).
2. The test's own query must already return the expected answer on that slice (else nothing is written).
3. The same reducer as `why` shrinks it with the `keep` predicate; the fixture is `<name>.rl` + `<name>.cypher`.
4. A pytest file is written beside it: it opens the fixture read-only and asserts the expected answer.

Nothing is ever written back to the remote: there is no `push` here, so a delete cannot reach Neo4j.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

from .check import relate_cli
from .guard import Refused, static_checks, strip_comments
from .pipeline import Outcome, Request, reduce_request, relate_version

TEST_TEMPLATE = '''"""Fixture test, generated by `witness fixture`.
Witness {witness_version}, relate-db {relate_version}.

The fixture is a {rels}-relationship graph pulled from Neo4j and shrunk until no single relationship could be removed
without changing this test's answer ({check_text}). Run it with: pytest {test_file}
"""

import json
from pathlib import Path

import relate

HERE = Path(__file__).parent
STATEMENT = {statement!r}
PARAMS = {params!r}
EXPECTED = {expected!r}


def test_{ident}_answer_on_the_fixture():
    db = relate.Database(str(HERE / "{name}.rl"), read_only=True)
    try:
        res = db.execute(STATEMENT, PARAMS)
        rows = json.loads(json.dumps(res.data))
    finally:
        db.close()
    key = lambda r: json.dumps(r, sort_keys=True)  # noqa: E731
    assert sorted(rows, key=key) == sorted(EXPECTED, key=key)
'''


def _ident(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in name)


def pull_slice(creds: Path, slice_query: str, dest: Path, params: dict | None = None) -> dict:
    # The slice runs on the user's Neo4j over the Query API: the same static guard as every other statement, so a
    # write, a procedure call or a ';' list never reaches the remote (a2a arch r1).
    static_checks(slice_query, params or {}, "--slice")
    try:
        names_a_file = slice_query.strip() == "-" or Path(slice_query.strip()).exists()
    except OSError:
        names_a_file = False
    if names_a_file:  # `relate pull --query` would read that file or stdin instead of the guarded text
        raise Refused("pass the slice statement text, not a file path or '-'", "--slice")
    cli, status = relate_cli()
    if cli is None:
        raise Refused(f"fixture mode needs the relate CLI for `relate pull`: {status}", "fixture")
    if dest.exists():
        raise Refused(f"pull refuses a non-empty destination: {dest} already exists", "fixture")
    cmd = [cli, "pull", "--from", str(creds), "--query", slice_query, "--database", str(dest)]
    for k, v in (params or {}).items():
        cmd += ["--param", f"{k}={json.dumps(v) if not isinstance(v, str) else v}"]
    t0 = time.perf_counter()
    p = subprocess.run(cmd, capture_output=True, text=True, env={**os.environ, "DO_NOT_TRACK": "1"}, timeout=600)
    secs = round(time.perf_counter() - t0, 3)
    if p.returncode != 0 or not dest.exists():
        tail = (p.stderr or p.stdout).strip().splitlines()[-1:] or ["no output"]
        raise Refused(f"relate pull failed (exit {p.returncode}): {tail[0][:300]}", "fixture")
    return {
        "seconds": secs,
        "cli": status,
        "stdout_tail": [ln.replace(str(dest), "<slice.rl>") for ln in p.stdout.strip().splitlines()[-3:]],
    }


def build_fixture(
    *,
    creds: Path,
    slice_query: str,
    statement: str,
    params: dict,
    expected: list,
    name: str,
    out_dir: Path,
    neo4j_image: str | None = None,
    progress=None,
) -> tuple[Outcome, dict]:
    out_dir = Path(out_dir)
    with tempfile.TemporaryDirectory(prefix="witness-fixture-") as td:
        slice_rl = Path(td) / "slice.rl"
        pulled = pull_slice(Path(creds), slice_query, slice_rl)
        req = Request(
            source=slice_rl,
            statement=statement,
            params=params,
            predicate="keep",
            name=name,
            out_dir=out_dir,
            ledger=None,
            requester="fixture",
            claimed=expected,
        )
        try:
            o = reduce_request(req, progress=progress)
        except Refused as e:
            if e.door == "answer":
                raise Refused(
                    "the test's expected answer is not what the pulled slice returns; the slice is too small or the "
                    "expectation is wrong. Nothing was written",
                    "fixture",
                ) from e
            raise
    # The slice lived in a temp dir: name it, not this machine's path (P1d QA r2: /var/folders/... was committed)
    o.manifest["source"]["path"] = "<slice.rl: temp store pulled from Neo4j>"
    man = Path(o.files["manifest"])
    m = json.loads(man.read_text())
    m["source"]["path"] = o.manifest["source"]["path"]
    man.write_text(json.dumps(m, indent=2, sort_keys=True) + "\n")
    report = {
        "name": name,
        "slice": {"nodes": o.source_counts[0], "relationships": o.source_counts[1], "pull_seconds": pulled["seconds"]},
        "fixture": {
            "nodes": o.run["final_counts"][0],
            "relationships": o.run["final_counts"][1],
            "trials": o.run["trials"],
            "reduction_seconds": o.run["seconds"],
            "inconclusive": o.run["inconclusive"],
        },
        "check": o.check.text if o.check else None,
        "verified": o.verified,
        "relate_cli": pulled["cli"],
        "relate_db": relate_version(),
        "neo4j_image": neo4j_image,
        "pull_tail": pulled["stdout_tail"],
        "never_pushed": True,
    }
    return o, report


def write_test_file(out_dir: Path, name: str, o: Outcome, statement: str, params: dict, expected: list) -> Path:
    from . import __version__

    test_file = f"test_{_ident(name)}.py"
    text = TEST_TEMPLATE.format(
        witness_version=__version__,
        relate_version=relate_version(),
        rels=o.run["final_counts"][1],
        check_text=(o.check.text.split(" (")[0] if o.verified else o.check.text) if o.check else "unchecked",
        test_file=test_file,
        statement=strip_comments(statement),
        params=params,
        expected=expected,
        ident=_ident(name),
        name=name,
    )
    p = Path(out_dir) / test_file
    p.write_text(text)
    return p


def which_docker_note() -> str:
    return "docker" if shutil.which("docker") else "no docker"
